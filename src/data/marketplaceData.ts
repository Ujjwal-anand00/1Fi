function getProductAsset(key: string) {
  try {
    switch (key) {
      case 'phone':
        return require('../../assets/products/smartphone.jpg');
      case 'laptop':
        return require('../../assets/products/laptop.jpg');
      case 'headphones':
        return require('../../assets/products/headphones.jpg');
      case 'smartwatch':
        return require('../../assets/products/smartwatch.jpg');
      case 'tablet':
        return require('../../assets/products/tablet.jpg');
      case 'tv':
        return require('../../assets/products/tv.jpg');
      case 'coffeeMaker':
        return require('../../assets/products/coffee_maker.jpg');
      default:
        return undefined;
    }
  } catch {
    return undefined;
  }
}

